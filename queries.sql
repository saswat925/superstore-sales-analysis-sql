-- 1.1 Convert ORDER_DATE and SHIP_DATE from VARCHAR to DATE
ALTER TABLE SUPERSTORE_DATA ADD COLUMN ORDER_DATE_CLEAN DATE;
ALTER TABLE SUPERSTORE_DATA ADD COLUMN SHIP_DATE_CLEAN DATE;

UPDATE SUPERSTORE_DATA
SET ORDER_DATE_CLEAN = TRY_TO_DATE(SPLIT_PART(ORDER_DATE, ' ', 1), 'DD-MM-YYYY'),
    SHIP_DATE_CLEAN  = TRY_TO_DATE(SPLIT_PART(SHIP_DATE, ' ', 1), 'DD-MM-YYYY');

ALTER TABLE SUPERSTORE_DATA DROP COLUMN ORDER_DATE;
ALTER TABLE SUPERSTORE_DATA DROP COLUMN SHIP_DATE;
ALTER TABLE SUPERSTORE_DATA RENAME COLUMN ORDER_DATE_CLEAN TO ORDER_DATE;
ALTER TABLE SUPERSTORE_DATA RENAME COLUMN SHIP_DATE_CLEAN TO SHIP_DATE;

