-- 1.3 Remove duplicate rows (38 duplicates)
CREATE OR REPLACE TABLE SUPERSTOREDB.PUBLIC.SUPERSTORE_DATA AS
SELECT * FROM (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY ORDER_ID, PRODUCT_ID ORDER BY ORDER_ID) AS RN
    FROM SUPERSTOREDB.PUBLIC.SUPERSTORE_DATA
) WHERE RN = 1;
ALTER TABLE SUPERSTOREDB.PUBLIC.SUPERSTORE_DATA DROP COLUMN RN;

-- 1.4 Standardize MARKET column
UPDATE SUPERSTOREDB.PUBLIC.SUPERSTORE_DATA
SET MARKET = CASE
    WHEN UPPER(MARKET) = 'US' THEN 'US'
    WHEN UPPER(MARKET) = 'EU' THEN 'EU'
    WHEN UPPER(MARKET) = 'APAC' THEN 'APAC'
    WHEN UPPER(MARKET) = 'LATAM' THEN 'LATAM'
    WHEN UPPER(MARKET) = 'EMEA' THEN 'EMEA'
    WHEN UPPER(MARKET) = 'AFRICA' THEN 'Africa'
    WHEN UPPER(MARKET) = 'CANADA' THEN 'Canada'
    ELSE INITCAP(MARKET)
END;

